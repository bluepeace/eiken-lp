/**
 * 技能LPの「その級・その技能ならでは」の解説（出題と話題／失点しやすい型／本番までの計画）
 *
 * ブログ（英検コラム）の同テーマ記事を下敷きにしているが、文章はLP用に書き直している。
 * 同じ文章を両方に載せると検索で評価を食い合うため、コピーはしない。
 * LPは「つまずき → AiKenのどの機能で直すか」に寄せ、詳しい解説はコラムへ送る。
 *
 * キー: [技能][級スラッグ]。データがないページでは、セクションごと表示しない。
 *
 * @return array{
 *   heading: string, intro: string,
 *   topics_heading: string, topics_lead: string, topics: string[], topics_note: string,
 *   traps_heading: string, traps: array<int, array{title: string, why: string, fix: string}>,
 *   plan_heading: string, plan_lead: string,
 *   plan: array<int, array{min_days: int, span: string, text: string}>
 * }|null
 * plan は min_days の大きい順。一次試験までの残り日数が min_days 以上の最初の段階に「今ここ」を付ける。
 */
function skill_deep_data(string $skill, string $grade): ?array
{
    static $data = null;
    if ($data === null) {
        $data = skill_deep_all();
    }
    return $data[$skill][$grade] ?? null;
}

