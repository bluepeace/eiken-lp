function faq_top_items(): array
{
    $items = [];
    foreach (faq_categories() as $cat) {
        foreach ($cat['items'] as $item) {
            if (!empty($item['on_top'])) {
                $items[] = $item;
            }
        }
    }
    return $items;
}

function faq_all_items(): array
{
    $items = [];
    foreach (faq_categories() as $cat) {
        foreach ($cat['items'] as $item) {
            $items[] = $item;
        }
    }
    return $items;
}
