function faq_monthly_price_answer(bool $with_plan_link = false): string
{
    $trial = FREE_TRIAL_DAYS . '日間の無料体験ののち、英検5級〜1級の対策機能をすべてご利用いただけます。';
    $tail = $with_plan_link ? '料金の詳細は「料金」ページもあわせてご確認ください。' : '詳しくは料金ページをご覧ください。';
    if (open_campaign_active()) {
        return 'プレミアムプランは今なら' . monthly_price_label() . 'です（OPEN記念価格・定価' . monthly_price_regular_label() . '・' . open_campaign_end_label() . 'まで）。' . $trial . $tail;
    }
    return 'プレミアムプランは' . monthly_price_regular_label() . 'です。' . $trial . $tail;
}

