/**
 * @return list<string>
 */
function listening_grade_slugs(): array
{
    return ['1kyu', 'jun1kyu', '2kyu', 'jun2kyu-plus', 'jun2kyu', '3kyu', '4kyu', '5kyu'];
}

function listening_page_path(string $slug): ?string
{
    if (!in_array($slug, listening_grade_slugs(), true)) {
        return null;
    }
    return '/' . $slug . '/listening/';
}

function listening_url(string $slug): string
{
    $path = listening_page_path($slug);
    if ($path === null) {
        return rtrim(SITE_URL, '/') . '/';
    }
    return rtrim(SITE_URL, '/') . $path;
}

function listening_signup_url(): string
{
    return rtrim(APP_URL, '/') . '/signup';
}

function listening_shot_url(string $slug, string $key): string
{
    if ($key === '') {
        return '';
    }
    $dir = __DIR__ . '/../assets/images/grade/' . $slug . '/';
    foreach (['.webp', '.jpg', '.png'] as $ext) {
        if (is_file($dir . $key . $ext)) {
            return '/assets/images/grade/' . rawurlencode($slug) . '/' . $key . $ext;
        }
    }
    return '';
}

/**
 * @param array<string, mixed> $grade
 * @param array<string, mixed> $content
 * @return array{title: string, description: string, og_type: string, robots: string, omit_jsonld: bool}
 */
function listening_meta(array $grade, array $content): array
{
    $name = (string) ($grade['name'] ?? '英検');
    return [
        'title' => $name . 'リスニング対策｜英検対策アプリ｜' . SITE_NAME,
        'description' => (string) ($content['description'] ?? ''),
        'og_type' => 'website',
        'robots' => '',
        'omit_jsonld' => false,
    ];
}

/**
 * @return list<array{slug: string, name: string, name_short: string, href: string}>
 */
function listening_nav_items(): array
{
    $items = [];
    foreach (listening_grade_slugs() as $slug) {
        $grade = get_grade($slug);
        $href = listening_page_path($slug);
        if ($grade === null || $href === null) {
            continue;
        }
        $items[] = [
            'slug' => $slug,
            'name' => (string) $grade['name'],
            'name_short' => (string) $grade['name_short'],
            'href' => $href,
        ];
    }
    return $items;
}

